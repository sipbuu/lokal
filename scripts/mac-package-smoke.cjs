const path = require('path')
const assert = require('assert/strict')
const { createRequire } = require('module')
const [resources, arch] = process.argv.slice(2)
const packagedRequire = createRequire(path.join(resources, 'app.asar/package.json'))
const Database = packagedRequire('better-sqlite3')
const db = new Database(':memory:')
assert.equal(db.prepare('SELECT 1 AS n').get().n, 1)
db.close()
const audio = packagedRequire(`./electron/native/audio-output.${process.platform}-${arch}.node`)
assert.equal(typeof audio.getDevices, 'function')
assert.equal(typeof audio.supportsExclusive(), 'boolean')
packagedRequire('sharp')({ create: { width: 1, height: 1, channels: 3, background: '#000000' } }).png().toBuffer().then(buffer => {
  assert.ok(buffer.length)
  console.log('Packaged Electron loaded SQLite, native audio, and sharp successfully')
}).catch(error => { console.error(error); process.exitCode = 1 })
